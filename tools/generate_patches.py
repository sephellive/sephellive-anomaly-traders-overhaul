#!/usr/bin/env python3
"""Generate DLTX sale-row removals from Anomaly and installed mod config roots."""
from __future__ import annotations
import argparse
import re
from pathlib import Path

SECTION = re.compile(r'^\s*\[([^\]]+)\]')
ENTRY = re.compile(r'^\s*([^;!#][^=]*?)\s*=')

def parse_sections(path: Path):
    section = None
    for line in path.read_text(encoding='utf-8-sig', errors='replace').splitlines():
        m = re.match(r'^\s*\[([^\]]+)\]', line)
        if m:
            section = m.group(1).strip()
        elif section:
            m = ENTRY.match(line)
            if m:
                yield section, m.group(1).strip()

def parse_trade_sections(path: Path):
    section = None
    parents: list[str] = []
    entries: list[str] = []
    def emit():
        if section is not None:
            return section, parents, entries
    for line in path.read_text(encoding='utf-8-sig', errors='replace').splitlines():
        header = re.match(r'^\s*!{0,2}\[([^\]]+)\]\s*(?::([^;]*))?\s*(?:;.*)?$', line)
        if header:
            previous = emit()
            if previous:
                yield previous
            section = header.group(1).strip()
            parents = [x.split(';', 1)[0].strip() for x in (header.group(2) or '').split(',')]
            parents = [x for x in parents if x]
            entries = []
        elif section is not None and (match := ENTRY.match(line)):
            entries.append(match.group(1).strip())
    previous = emit()
    if previous:
        yield previous

def parse_definitions(path: Path):
    section = None
    parents = []
    cls = None
    def emit():
        if section:
            yield section, parents, cls
    for line in path.read_text(encoding='utf-8-sig', errors='replace').splitlines():
        m = re.match(r'^\s*\[([^\]]+)\]\s*(?::([^;]*))?\s*(?:;.*)?$', line)
        if m:
            yield from emit()
            section = m.group(1).strip()
            parents = [x.split(';', 1)[0].strip() for x in (m.group(2) or '').split(',') if x.split(';', 1)[0].strip()]
            cls = None
        elif section and (m := re.match(r'^\s*class\s*=\s*([^;\s]+)', line, re.I)):
            cls = m.group(1).upper()
    yield from emit()

def item_kind_map(config_roots: list[Path]) -> dict[str, str]:
    defs = {}
    for configs in config_roots:
        for p in (configs / 'items').rglob('*.ltx'):
            rel = p.relative_to(configs).as_posix().casefold()
            for sec, parents, cls in parse_definitions(p):
                kind = 'outfit' if '/outfits/' in f'/{rel}' and cls in {'EQU_STLK', 'E_STLK', 'E_HLMET'} else None
                if '/weapons/' in f'/{rel}' and cls and cls.startswith('WP_') and cls not in {'WP_SCOPE','WP_SILEN','WP_BINOC'}:
                    kind = 'weapon'
                key = sec.casefold()
                old_kind, old_parents = defs.get(key, (None, []))
                defs[key] = (kind or old_kind, [x.casefold() for x in parents] or old_parents)
    result = {}
    def resolve(key, seen=None):
        seen = set() if seen is None else seen
        if key in seen or key not in defs: return None
        seen.add(key)
        kind, parents = defs[key]
        if kind: return kind
        for parent in parents:
            found = resolve(parent, seen)
            if found: return found
        return None
    for key in defs:
        kind = resolve(key)
        if kind: result[key] = kind
        elif key.startswith('helm_'):
            result[key] = 'outfit'
        elif key.endswith('_outfit'):
            result[key] = 'outfit'
    return result

def find_config_roots(inputs: list[Path]) -> list[Path]:
    found = []
    for root in inputs:
        if (root / 'configs').is_dir():
            found.append(root / 'configs')
        elif (root / 'gamedata' / 'configs').is_dir():
            found.append(root / 'gamedata' / 'configs')
        elif root.name.casefold() == 'mods':
            found.extend(p for p in root.glob('*/gamedata/configs') if p.is_dir())
        else:
            found.append(root)
    return list(dict.fromkeys(found))

def roots_from_profile(profile: Path, mods_dir: Path) -> list[Path]:
    enabled = []
    for line in (profile / 'modlist.txt').read_text(encoding='utf-8-sig').splitlines():
        if line.startswith('+'):
            folder = mods_dir / line[1:].strip()
            if (folder / 'gamedata' / 'configs').is_dir():
                enabled.append(folder / 'gamedata' / 'configs')
    return enabled

def render_patch(deletes: dict[str, set[str]]) -> str:
    """Render DLTX overrides without replacing their target sections."""
    lines = ['; Generated by Sephellive Traders Overhaul. Do not edit source trade files.']
    for section in sorted(deletes, key=str.casefold):
        if not section.casefold().startswith('supplies_') and section.casefold() != 'common_stock':
            raise ValueError(f'Only trader supply sections can be patched: {section}')
        lines.extend(['', f'![{section}]'])
        lines.extend(f'!{key} =' for key in sorted(deletes[section], key=str.casefold))
    return '\n'.join(lines) + '\n'

def discover_trade_targets(config_roots: list[Path]):
    base_files: dict[str, list[Path]] = {}
    overlay_files: list[tuple[str, Path]] = []
    for configs in config_roots:
        trade_dir = configs / 'items' / 'trade'
        if not trade_dir.is_dir():
            continue
        for path in trade_dir.rglob('*.ltx'):
            name = path.name.casefold()
            rel = path.relative_to(configs).as_posix().casefold()
            if name.startswith('trade_'):
                base_files.setdefault(rel, []).append(path)
            elif name.startswith('mod_trade_'):
                overlay_files.append((rel, path))

    targets = {rel: list(paths) for rel, paths in base_files.items()}
    unmatched = []
    for rel, path in overlay_files:
        stem = path.stem.casefold()[len('mod_'):]
        parent = Path(rel).parent
        candidates = [Path(base_rel) for base_rel in base_files
                      if Path(base_rel).parent == parent
                      and (stem == Path(base_rel).stem.casefold()
                           or stem.startswith(Path(base_rel).stem.casefold() + '_'))]
        if not candidates:
            unmatched.append(rel)
            continue
        target = max(candidates, key=lambda item: len(item.stem)).as_posix().casefold()
        targets[target].append(path)
    return targets, unmatched

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--config-root', action='append', required=True, type=Path,
                    help='Root containing configs/ (repeat in MO2 priority order)')
    ap.add_argument('--output', required=True, type=Path, help='Addon gamedata/configs directory')
    ap.add_argument('--mo2-profile', type=Path, help='MO2 profile folder; scans enabled mods only')
    ap.add_argument('--mo2-mods', type=Path, help='MO2 mods folder used with --mo2-profile')
    args = ap.parse_args()
    for old in args.output.rglob('mod_*_sto_v1.ltx') if args.output.exists() else ():
        old.unlink()
    roots = find_config_roots(args.config_root)
    if args.mo2_profile:
        if not args.mo2_mods:
            ap.error('--mo2-mods is required with --mo2-profile')
        roots.extend(roots_from_profile(args.mo2_profile, args.mo2_mods))
    roots = list(dict.fromkeys(roots))
    trade_paths, unmatched = discover_trade_targets(roots)
    classifications = item_kind_map(list(dict.fromkeys(roots)))
    parents_by_section: dict[str, set[str]] = {}
    for paths in trade_paths.values():
        for path in paths:
            for section, parents, _ in parse_trade_sections(path):
                parents_by_section.setdefault(section.casefold(), set()).update(p.casefold() for p in parents)
    eligible_sections = {name for name in parents_by_section if name.startswith('supplies_')}
    pending = list(eligible_sections)
    while pending:
        current = pending.pop()
        for parent in parents_by_section.get(current, set()):
            if parent not in eligible_sections:
                eligible_sections.add(parent)
                pending.append(parent)
    unresolved_forbidden = []
    for rel in unmatched:
        for configs in roots:
            path = configs / rel
            if not path.is_file():
                continue
            for section, _, keys in parse_trade_sections(path):
                for key in keys:
                    category = classifications.get(key.casefold())
                    if not category and (key.casefold().startswith('helm_') or key.casefold().endswith('_outfit')):
                        category = 'outfit'
                    if section.casefold() in eligible_sections and category in {'weapon', 'outfit'}:
                        unresolved_forbidden.append(f'{rel}: [{section}] {key}')
    if unresolved_forbidden:
        raise SystemExit('Unmatched active DLTX overlays contain forbidden sale entries:\n' + '\n'.join(unresolved_forbidden))
    if unmatched:
        print(f'Ignored {len(unmatched)} unmatched active trade overlay(s) with no forbidden sale rows.')

    count = 0
    for rel, paths in trade_paths.items():
        # Analyze every installed version of a shared virtual path; emitted deletes
        # are the union so the overlays also remove entries reintroduced upstream.
        deletes: dict[str, set[str]] = {}
        for p in paths:
            for sec, _, keys in parse_trade_sections(p):
                if sec.casefold() not in eligible_sections:
                    continue
                for key in keys:
                    category = classifications.get(key.casefold())
                    if not category and (key.casefold().startswith('helm_') or key.casefold().endswith('_outfit')):
                        category = 'outfit'
                    if category in {'weapon', 'outfit'}:
                        deletes.setdefault(sec, set()).add(key)
        if not deletes:
            continue
        relpath = Path(rel)
        out_dir = args.output / relpath.parent
        out_dir.mkdir(parents=True, exist_ok=True)
        out = out_dir / f'mod_{relpath.stem}_sto_v1.ltx'
        count += sum(map(len, deletes.values()))
        out.write_text(render_patch(deletes), encoding='utf-8')
    print(f'Generated {count} unique sale-row deletions across {len(trade_paths)} trade config paths.')

if __name__ == '__main__':
    main()
